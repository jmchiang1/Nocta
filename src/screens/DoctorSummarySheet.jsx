/* Nocta — doctor summary. The doctor path: a hard-escalation why-card opens
 * this instead of suggesting a self-fix. It shows what made Nocta suggest it
 * (the insight's own cited numbers, no interpretation) and what goes into the
 * one-page summary. Per FEATURES › Doctor PDF export, it carries numbers only
 * — no AI commentary. The export is real (lib/doctorReport.js): a printable
 * page of the last 30 nights, opened to print or save as PDF. */
import { useStore } from '../lib/store.jsx';
import { FIXTURES } from '../data/fixtures.js';
import { openDoctorReport, REPORT_DAYS } from '../lib/doctorReport.js';
import { Sheet } from '../components/Sheet.jsx';
import { Icon } from '../components/Icons.jsx';

const CONTENTS = [
  'AHI for each night, with a chart',
  'Obstructive, central and hypopnea events',
  'Leak each night (95th percentile)',
  'The pressure your machine ran at, and its prescribed range',
  'Hours of use each night, and nights over 4 hours',
];

function fmt(c) {
  const unit = c.unit === 'events/hr' ? ' an hour' : c.unit === 'count' ? '' : ` ${c.unit}`;
  return `${c.value}${unit}`;
}

export function DoctorSummarySheet() {
  const { closeSheet, fixtureId, showToast } = useStore();
  const fx = FIXTURES[fixtureId];

  const reasons = fx.insight.data_citations.map((c) => ({ k: c.metric, v: fmt(c) }));

  function open() {
    if (!openDoctorReport()) showToast('Allow pop-ups for Nocta to open the summary', 'info');
  }

  return (
    <Sheet
      eyebrow="For your doctor"
      title="Doctor summary"
      onClose={closeSheet}
      footer={
        <button className="btn primary" onClick={open}>
          Open the summary
        </button>
      }
    >
      <div className="doc-sheet">
        <p className="doc-lede">
          Your last {REPORT_DAYS} nights on one page, to bring to your next appointment. It opens
          ready to print or save as a PDF. It shows your numbers only, with no Nocta commentary,
          so your doctor can read it their way.
        </p>

        <section className="doc-block" aria-labelledby="doc-why">
          <h4 id="doc-why">Why Nox suggested this</h4>
          <dl className="doc-reasons">
            {reasons.map((r) => (
              <div key={r.k}>
                <dt>{r.k}</dt>
                <dd className="tnum">{r.v}</dd>
              </div>
            ))}
          </dl>
          <p className="doc-note">
            This is a pattern for your sleep doctor to look at. Keep using your machine as
            prescribed and don't change your settings on your own.
          </p>
        </section>

        <section className="doc-block" aria-labelledby="doc-what">
          <h4 id="doc-what">What's on it</h4>
          <ul className="doc-contents">
            {CONTENTS.map((c) => (
              <li key={c}>
                <Icon name="check" size={15} />
                {c}
              </li>
            ))}
          </ul>
        </section>

        <p className="doc-note">
          Generated by Nocta from your CPAP’s SD card. Not a medical record.
        </p>
      </div>
    </Sheet>
  );
}
